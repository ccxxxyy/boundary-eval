def truth() -> dict:
    return {code: {"revenue": r, "fcf": c - x} for code, (r, c, x) in RAW.items()}


def ranking() -> list:
    t = truth()
    return sorted(t, key=lambda code: t[code]["fcf"], reverse=True)


if __name__ == "__main__":
    for code in ranking():
        v = truth()[code]
        print(code, NAMES[code], f"revenue={v['revenue']:,.2f}", f"fcf={v['fcf']:,.2f}")
