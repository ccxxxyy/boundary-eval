from decimal import Decimal as D
# 金额均已按报表单位换算为元；capex 取支付现金的正数金额
raw={
'600519':('168838102514.79','61522204989.35','3127594916.41'),
'000333':('456451731000','53345930000','11141889000'),
'300750':('423701834000','133219982000','42344558000'),
'002594':('803964958000','59135544000','156807853000'),
'600900':('86241940222.20','60562925570.41','18488466859.29'),
'000858':('40528509770.23','29706259919.13','1967407316.36'),
'600309':('203234573814.42','33105189455.82','30711201211.89'),
'000651':('170447058533.57','46383114754.02','1717311068.10'),
'600276':('31629416193.83','11235378130.63','2961906284.58'),
'002415':('92507796069.94','25339411083.10','3622046664.67'),
'601012':('70347049950.42','4359382755.77','5893972740.27')}
res={}
for code,(rev,cfo,capex) in raw.items():
    rev,cfo,capex=map(D,(rev,cfo,capex))
    res[code]={'revenue':rev,'fcf':cfo-capex}
    print(code,'revenue=',rev,'CFO=',cfo,'capex=',capex,'FCF=',cfo-capex)
ranking=sorted(res,key=lambda c:res[c]['fcf'],reverse=True)
print('\nRANKING')
for c in ranking: print(c,res[c]['fcf'])
# 千元报表换算交叉核对
assert D('456451731')*1000==res['000333']['revenue']
assert D('423701834')*1000==res['300750']['revenue']
assert D('803964958')*1000==res['002594']['revenue']
assert (D('53345930')-D('11141889'))*1000==res['000333']['fcf']
assert (D('133219982')-D('42344558'))*1000==res['300750']['fcf']
assert (D('59135544')-D('156807853'))*1000==res['002594']['fcf']
print('\nAll conversion checks passed.')
